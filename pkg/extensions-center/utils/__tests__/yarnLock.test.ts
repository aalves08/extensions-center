import { parseYarnLock, specifierName } from '../yarnLock';

describe('specifierName', () => {
  it.each([
    ['lodash@^4.17.0', 'lodash'],
    ['lodash@4.17.21', 'lodash'],
    ['@scope/pkg@^1.0.0', '@scope/pkg'],
    ['@scope/pkg@npm:^1.0.0', '@scope/pkg'],
    ['@rancher/shell@npm:3.0.13', '@rancher/shell'],
  ])('reads %s as %s', (spec, expected) => {
    expect(specifierName(spec)).toBe(expected);
  });

  it('strips surrounding quotes', () => {
    expect(specifierName('"@scope/pkg@npm:^1.0.0"')).toBe('@scope/pkg');
  });

  it('ignores surrounding whitespace', () => {
    expect(specifierName('  lodash@^4.0.0  ')).toBe('lodash');
  });

  it('returns null for a scoped name carrying no range', () => {
    // The only '@' is the scope marker at index 0, so there is no separator.
    expect(specifierName('@scope/pkg')).toBeNull();
  });

  it('returns null for a bare name with no range', () => {
    expect(specifierName('lodash')).toBeNull();
  });

  it('returns null for an empty specifier', () => {
    expect(specifierName('')).toBeNull();
    expect(specifierName('   ')).toBeNull();
  });

  it('splits on the last @, so a range containing one survives', () => {
    expect(specifierName('pkg@npm:@scope/other@1.0.0')).toBe('pkg@npm:@scope/other');
  });
});

describe('parseYarnLock', () => {
  it('parses a classic v1 lockfile', () => {
    const lock = `# THIS IS AN AUTOGENERATED FILE
# yarn lockfile v1


lodash@^4.17.0:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"
  integrity sha512-abc

vue@^3.4.0:
  version "3.4.21"
  resolved "https://registry.yarnpkg.com/vue/-/vue-3.4.21.tgz"
`;

    expect(parseYarnLock(lock)).toEqual(new Map([
      ['lodash', ['4.17.21']],
      ['vue', ['3.4.21']],
    ]));
  });

  it('parses a Berry lockfile, skipping its __metadata block', () => {
    const lock = `__metadata:
  version: 8
  cacheKey: 10c0

"lodash@npm:^4.17.0":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"

"@rancher/shell@npm:^3.0.13":
  version: 3.0.13
  resolution: "@rancher/shell@npm:3.0.13"
`;

    const out = parseYarnLock(lock);

    expect(out.get('lodash')).toEqual(['4.17.21']);
    expect(out.get('@rancher/shell')).toEqual(['3.0.13']);
    expect(out.has('__metadata')).toBe(false);
  });

  it('attributes one version to every specifier sharing a header', () => {
    const lock = `lodash@^4.17.0, lodash@^4.17.15, lodash@~4.17.20:
  version "4.17.21"
`;

    expect(parseYarnLock(lock).get('lodash')).toEqual(['4.17.21']);
  });

  it('keeps every version a name resolves to, not just one', () => {
    // Nested node_modules are real and matter: one of these may be vulnerable.
    const lock = `lodash@^4.17.0:
  version "4.17.21"

lodash@^3.0.0:
  version "3.10.1"
`;

    expect(parseYarnLock(lock).get('lodash')).toEqual(['3.10.1', '4.17.21']);
  });

  it('deduplicates a version resolved twice', () => {
    const lock = `lodash@^4.17.0:
  version "4.17.21"

lodash@^4.17.15:
  version "4.17.21"
`;

    expect(parseYarnLock(lock).get('lodash')).toEqual(['4.17.21']);
  });

  it('skips an entry whose body carries no version rather than throwing', () => {
    const lock = `broken@^1.0.0:
  resolved "https://example.com/broken.tgz"

lodash@^4.17.0:
  version "4.17.21"
`;

    const out = parseYarnLock(lock);

    expect(out.has('broken')).toBe(false);
    expect(out.get('lodash')).toEqual(['4.17.21']);
  });

  it('ignores a nested version field after the entry\'s own', () => {
    // `dependencies` blocks carry version *ranges*, not resolutions; reading
    // one as the entry's version would record '^4.0.0' as a resolved version.
    const lock = `pkg@^1.0.0:
  version "1.2.3"
  dependencies:
    lodash "^4.0.0"
    version "9.9.9"
`;

    expect(parseYarnLock(lock).get('pkg')).toEqual(['1.2.3']);
  });

  it('handles tab indentation as well as spaces', () => {
    expect(parseYarnLock('pkg@^1.0.0:\n\tversion "1.2.3"\n').get('pkg')).toEqual(['1.2.3']);
  });

  it('ignores comments and blank lines', () => {
    expect(parseYarnLock('\n# a comment\n\n')).toEqual(new Map());
  });

  it('returns an empty map for an empty lockfile', () => {
    expect(parseYarnLock('')).toEqual(new Map());
  });

  it('ignores an indented version with no header above it', () => {
    expect(parseYarnLock('  version "1.2.3"\n')).toEqual(new Map());
  });

  it('sorts the versions it returns', () => {
    const lock = `pkg@a:
  version "2.0.0"

pkg@b:
  version "1.0.0"
`;

    expect(parseYarnLock(lock).get('pkg')).toEqual(['1.0.0', '2.0.0']);
  });
});
